"""Writes js/ai/weights.js from the fitted model files the Python bots use, so the browser
bots (js/ai/) load the same numbers:

    python3 tools/export_ai_weights.py

ai/value_weights.json  value model, P(detectives win) of a position (ai/value.py)
ai/move_weights.json   fugitive move model behind the location estimate (ai/policies.py)

tests/ai_parity.test.js fails if the two drift apart.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    out = {}
    for name, f in (('value', 'value_weights.json'), ('move', 'move_weights.json')):
        d = json.loads((ROOT / 'ai' / f).read_text())
        out[name] = {'features': d['features'], 'weights': d['weights']}
    text = ('/* Generated by tools/export_ai_weights.py from ai/value_weights.json and '
            'ai/move_weights.json. Do not edit by hand. */\n'
            '(function (root) {\n'
            f'  const WEIGHTS = {json.dumps(out)};\n'
            "  if (typeof module === 'object' && module.exports) module.exports = WEIGHTS;\n"
            '  else root.AIWeights = WEIGHTS;\n'
            "})(typeof self !== 'undefined' ? self : this);\n")
    (ROOT / 'js' / 'ai' / 'weights.js').write_text(text)
    print('wrote js/ai/weights.js')


if __name__ == '__main__':
    main()
